const eventPl = (p: AuditParams) => LOG_EVENT_NAMES_PL[String(p.event)] ?? String(p.event);
const eventEn = (p: AuditParams) => logEventTextEn[String(p.event)]?.name ?? String(p.event);
const num = (p: AuditParams, key: string) => Number(p[key] ?? 0);

const COUNTER_PL: Record<string, string> = { lastJoined: "ostatnio dołączył", users: "liczba użytkowników", bots: "liczba botów", bans: "liczba banów" };
const COUNTER_EN: Record<string, string> = { lastJoined: "latest member", users: "member count", bots: "bot count", bans: "ban count" };

function plCount(n: number, one: string, few: string, many: string): string {
  if (n === 1) return one;
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 >= 2 && mod10 <= 4 && !(mod100 >= 12 && mod100 <= 14)) return few;
  return many;
}

